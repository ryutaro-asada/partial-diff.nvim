local helpers = require('helpers')

describe('setup()', function()
  it('has sensible diff defaults', function()
    local pd = helpers.fresh_plugin()
    assert.is_false(pd.diff.compute_moves)
    assert.is_false(pd.diff.ignore_trim_whitespace)
    assert.is_true(pd.diff.sync_scroll)
    assert.is_true(pd.diff.sync_scroll_nowrap)
    assert.truthy(pd.diff.fallback_diffopt:find('algorithm:histogram', 1, true))
    assert.truthy(pd.diff.fallback_diffopt:find('linematch:60', 1, true))
  end)

  it('merges known diff options and ignores unknown ones', function()
    local pd = helpers.fresh_plugin({ diff = { compute_moves = true, sync_scroll = false, bogus = 1 } })
    assert.is_true(pd.diff.compute_moves)
    assert.is_false(pd.diff.sync_scroll)
    assert.is_true(pd.diff.sync_scroll_nowrap)
    assert.is_nil(pd.diff.bogus)
  end)

  it('lets a highlight table override the default link', function()
    local pd = helpers.fresh_plugin({
      highlights = { char_change = { bg = '#4a4a0e', fg = '#ffd866', bold = true } },
    })
    pd.setup_highlights()
    local hl = vim.api.nvim_get_hl(0, { name = 'PartialDiffCharChange' })
    assert.is_nil(hl.link)
    assert.are.equal(0x4a4a0e, hl.bg)
    assert.are.equal(0xffd866, hl.fg)
    assert.is_true(hl.bold)
  end)

  it('treats a highlight string as a link', function()
    local pd = helpers.fresh_plugin({ highlights = { char_change = 'Search' } })
    pd.setup_highlights()
    assert.are.equal('Search', vim.api.nvim_get_hl(0, { name = 'PartialDiffCharChange' }).link)
  end)

  it('keeps the default link when no highlights are configured', function()
    local pd = helpers.fresh_plugin()
    pd.setup_highlights()
    assert.are.equal('DiffText', vim.api.nvim_get_hl(0, { name = 'PartialDiffCharChange' }).link)
  end)

  it('defines the move highlight group', function()
    local pd = helpers.fresh_plugin()
    pd.setup_highlights()
    local hl = vim.api.nvim_get_hl(0, { name = 'PartialDiffLineMove' })
    assert.are.equal(0x2d3a5a, hl.bg)
  end)
end)
